export const DEFAULT_ICON = 'kiste';

/**
 * Erzeugt ein Symbol als <svg>.
 *   icon('dose')                     -> mit Aquarell-Klecks
 *   icon('plus', { wash: false })    -> nur Linien
 *   icon('korb', { label: 'Liste' }) -> mit Text für Screenreader
 */
export function icon(name, { wash = true, label, className } = {}) {
  const def = ICONS[name] || ICONS[DEFAULT_ICON];
  const svg = el('svg', {
    viewBox: '0 0 48 48',
    class: ['art', className].filter(Boolean).join(' '),
    'aria-hidden': label ? null : 'true',
    role: label ? 'img' : null,
    'aria-label': label || null,
    focusable: 'false',
  });
  if (wash && def.wash) {
    // leicht versetzt = wie von Hand koloriert
    svg.append(el('path', { d: def.wash, class: 'art__wash' }));
  }
  const ink = el('g', { class: 'art__ink' });
  for (const d of def.ink || []) ink.append(el('path', { d }));
  for (const [cx, cy] of def.dots || []) ink.append(el('circle', { cx, cy, r: 1.3, class: 'art__dot' }));
  svg.append(ink);
  return svg;
}

function el(tag, attrs) {
  const node = document.createElementNS(SVG_NS, tag);
  for (const [k, v] of Object.entries(attrs)) if (v != null) node.setAttribute(k, String(v));
  return node;
}
